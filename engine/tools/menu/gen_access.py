"""Settings > Accessibility's menu styles -> engine/ui/rcss/access/<page>.rcss.

python engine/tools/menu/gen_access.py

The UI merges a page's access file into it as it loads (oz_ui.cpp LoadPage) and sets two classes on
each page's body from the settings:
  - body.hc (High-contrast menus): dim text brighter, translucent text solid, the dark see-through
    boxes (panels, dialogs, fields, tables) opaque;
  - body.calm (Reduced flashing): no pulsing or blinking animations (an infinite alternate one).

A page's rules come from its own styles: the rules of the style sheets it links and of its <style>
blocks that set such a color, background or animation, under the class. So a rule reaches only the
pages its source does. Run it again after changing the menus' styles.
"""
import os, re, glob

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
UI = os.path.join(ROOT, "ui")
OUT = os.path.join(UI, "rcss", "access")
# the Settings page is generated (oz_ui_settings.cpp Settings_PageRml): its links
GENERATED = {"settings": ["menu.rcss", "settings.rcss"]}

# the menus' dim text colors and what they become
TEXT = {"#8d847c": "#d9d0c6", "#5d554f": "#b0a79e"}
# dark backgrounds that go opaque: black and the panels' near-black, at any alpha
DARK = ("#000000", "#0a0807")
# overlays meant to show what's under them (a locked card's veil, the crosshair preview's), left as they are
KEEP = {".lock", ".lockov", ".veil"}


def strip_blocks(css, at):
    """css without its @<at> blocks (their braces nest)."""
    out, i = [], 0
    while True:
        j = css.find(at, i)
        if j < 0:
            return "".join(out) + css[i:]
        out.append(css[i:j])
        k = css.index("{", j)
        depth = 0
        while True:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
                if depth == 0:
                    break
            k += 1
        i = k + 1


def rules(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = strip_blocks(css, "@keyframes")
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
        sel = " ".join(m.group(1).split())
        decls = [d.strip() for d in m.group(2).split(";") if ":" in d]
        yield sel, [(d.split(":", 1)[0].strip(), d.split(":", 1)[1].strip()) for d in decls]


def under(cls, sel):
    """Each selector of a list under body.<cls>."""
    out = []
    for s in sel.split(","):
        s = s.strip()
        if s == "body" or s.startswith("body.") or s.startswith("body "):
            out.append("body." + cls + s[4:])
        else:
            out.append("body.%s %s" % (cls, s))
    return ", ".join(out)


def hc(decls, sel):
    out = []
    for name, value in decls:
        v = value.lower()
        if name == "color" and v.startswith("#"):
            if v[:7] in TEXT:
                out.append("color: %s" % TEXT[v[:7]])
            elif len(v) == 9:
                out.append("color: %s" % v[:7])
        elif name == "background-color" and v.startswith("#") and len(v) == 9 and v[:7] in DARK and sel not in KEEP:
            out.append("background-color: %s" % v[:7])
    return out


def calm(decls):
    for name, value in decls:
        if name == "animation" and "infinite" in value and "alternate" in value:
            return ["animation: none"]
    return []


def block(text):
    out = []
    for sel, decls in rules(text):
        for cls, new in (("hc", hc(decls, sel)), ("calm", calm(decls))):
            if new:
                out.append("%s { %s; }" % (under(cls, sel), "; ".join(new)))
    return out


def main():
    pages = {}
    for path in sorted(glob.glob(os.path.join(UI, "pages", "*.rml"))):
        rml = open(path, encoding="utf-8").read()
        links = re.findall(r'href="\.\./rcss/([\w.-]+\.rcss)"', rml)
        pages[os.path.splitext(os.path.basename(path))[0]] = (links, re.findall(r"<style>(.*?)</style>", rml, re.S))
    for name, links in GENERATED.items():
        pages[name] = (links, [])
    os.makedirs(OUT, exist_ok=True)
    for old in glob.glob(os.path.join(OUT, "*.rcss")):
        os.remove(old)
    total = 0
    for name, (links, styles) in sorted(pages.items()):
        lines = ["/* Settings > Accessibility for %s: generated by engine/tools/menu/gen_access.py from its styles; don't edit. */" % name, ""]
        count = 0
        sources = [("rcss/" + l, open(os.path.join(UI, "rcss", l), encoding="utf-8").read()) for l in links]
        sources += [("pages/%s.rml" % name, t) for t in styles]
        for src, text in sources:
            b = block(text)
            if b:
                lines += ["/* %s */" % src] + b + [""]
                count += len(b)
        if count:
            open(os.path.join(OUT, name + ".rcss"), "w", encoding="utf-8", newline="\n").write("\n".join(lines))
            total += count
    print("%s: %d pages, %d rules" % (os.path.relpath(OUT, ROOT), len(glob.glob(os.path.join(OUT, "*.rcss"))), total))


if __name__ == "__main__":
    main()
