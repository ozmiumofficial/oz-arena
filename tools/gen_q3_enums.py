"""Writes scripts/game/q3_enums.gd from id's headers, so the Godot side uses the game code's own
numbering (events, entity types, weapons, animations, stats, means of death, configstrings).

python gen_q3_enums.py   (reads tools/q3core/thirdparty/ioq3, writes into tools/godot_template)
"""
import os, re, json

HERE = os.path.dirname(os.path.abspath(__file__))
CODE = os.path.join(HERE, "q3core", "thirdparty", "ioq3", "code")
OUT = os.path.join(HERE, "godot_template", "scripts", "game", "q3_enums.gd")

bg = open(os.path.join(CODE, "game", "bg_public.h"), encoding="latin-1").read()
qs = open(os.path.join(CODE, "qcommon", "q_shared.h"), encoding="latin-1").read()
bg = re.sub(r"#ifdef MISSIONPACK.*?#endif", lambda m: "", bg, flags=re.S) if False else bg


def enum_names(text, typedef):
    """Names of a C enum `typedef enum { ... } typedef;`, in order (MISSIONPACK blocks kept, as
    ioquake3 numbers them the same in baseq3 builds only when they're outside #ifdef)."""
    end = re.search(r"\}\s*" + typedef + r"\s*;", text)
    start = text.rfind("typedef enum", 0, end.start())
    body = text[text.index("{", start) + 1:end.start()]
    # drop #ifdef MISSIONPACK ... #endif sections (baseq3 is built without MISSIONPACK)
    body = re.sub(r"#ifdef\s+MISSIONPACK.*?#endif", "", body, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    names, value = [], 0
    for item in body.split(","):
        item = item.strip()
        if not item or item.startswith("#"):
            continue
        item = item.split("\n")[-1].strip() if "#" in item else item
        if "=" in item:
            n, v = [x.strip() for x in item.split("=", 1)]
            try:
                value = int(v, 0)
            except ValueError:
                continue
        else:
            n = item
        if re.match(r"^[A-Z_][A-Z0-9_]*$", n):
            names.append((n, value))
            value += 1
    return names


def defines(text, prefix):
    out = []
    for n, v in re.findall(r"#define\s+(" + prefix + r"[A-Z0-9_]*)\s+([^\s/]+)", text):
        out.append((n, v))
    return out


lines = ["class_name Q3Enums", "extends RefCounted",
         "## id Tech 3's numbering from the game code headers (bg_public.h, q_shared.h), generated by",
         "## tools/gen_q3_enums.py; don't edit by hand.", ""]
for typedef, comment in [("entityType_t", "entity types (entityState_t.eType)"),
                         ("entity_event_t", "entity events (es.event & ~EV_EVENT_BITS, ps.events)"),
                         ("weapon_t", "weapons"), ("animNumber_t", "player animations (legsAnim/torsoAnim & ~ANIM_TOGGLEBIT)"),
                         ("powerup_t", "powerups (ps.powerups index, es.powerups bit)"), ("holdable_t", "holdable items"),
                         ("statIndex_t", "ps.stats indexes"), ("persEnum_t", "ps.persistant indexes"),
                         ("meansOfDeath_t", "means of death (obituaries)"), ("itemType_t", "item types"),
                         ("pmtype_t", "ps.pm_type"), ("team_t", "teams"), ("gametype_t", "g_gametype")]:
    names = enum_names(bg if re.search(r"\}\s*%s\s*;" % typedef, bg) else qs, typedef)
    lines.append("# " + comment)
    lines.append("enum {")
    for n, v in names:
        lines.append("\t%s = %d," % (n, v))
    lines.append("}")
    short = {"animNumber_t": "ANIM", "entity_event_t": "EVENT", "weapon_t": "WEAPON", "meansOfDeath_t": "MOD"}.get(typedef)
    if short:
        listed = [""] * (max(v for _, v in names) + 1)
        for n, v in names:
            listed[v] = n
        lines.append("const %s_NAMES := %s" % (short, json.dumps(listed)))
    lines.append("")

const = []
for n, v in defines(bg, "(?:EV_EVENT_BIT|EV_EVENT_BITS|ANIM_TOGGLEBIT|DEFAULT_VIEWHEIGHT|CROUCH_VIEWHEIGHT|DEAD_VIEWHEIGHT|EF_|PMF_|BUTTON_|GIB_HEALTH)"):
    const.append((n, v))
for n, v in defines(qs, "(?:BUTTON_|CS_|MAX_CLIENTS|ENTITYNUM_|MAX_GENTITIES|MAX_MODELS|MAX_SOUNDS|SOLID_BMODEL)"):
    const.append((n, v))
for n, v in defines(bg, "CS_"):
    const.append((n, v))
seen = set()
known = {}
for n, v in const:
    if n in seen:
        continue
    seen.add(n)
    expr = v
    for k in sorted(known, key=len, reverse=True):
        expr = re.sub(r"\b%s\b" % k, str(known[k]), expr)
    expr = expr.replace("(", "").replace(")", "")
    try:
        val = eval(expr.replace("<<", " << "), {})
    except Exception:
        continue
    known[n] = val
    lines.append("const %s := %d" % (n, val))
# q_math.c bytedirs: the 162 directions events send as one byte (DirToByte / ByteToDir)
qm = open(os.path.join(CODE, "qcommon", "q_math.c"), encoding="latin-1").read()
body = re.search(r"bytedirs\[NUMVERTEXNORMALS\]\s*=\s*\{(.*?)\};", qm, re.S).group(1)
nums = [float(x) for x in re.findall(r"-?\d+\.\d+", body)]
dirs = [nums[i:i + 3] for i in range(0, len(nums), 3)]
lines.append("## q_math.c bytedirs (id axes): ByteToDir for event parameters")
lines.append("const BYTEDIRS := [" + ", ".join("Vector3(%g, %g, %g)" % tuple(d) for d in dirs) + "]")
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote", OUT, len(lines), "lines")
